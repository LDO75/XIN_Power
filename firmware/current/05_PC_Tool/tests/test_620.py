    def test_upgrade_entire_state_machine_over_binary(self):
        from updater_protocol import perform_upgrade
        from firmware_image import FirmwareImage
        import zlib,hashlib
        data=bytes(range(256))*2
        image=FirmwareImage(Path('mock.bin'),data,'6.2.0',60200,zlib.crc32(data),hashlib.sha256(data).hexdigest())
        class UpgradePort(FakePort):
            def __init__(self):super().__init__();self.received=0;self.total=0
            def write(self,wire):
                self.writes.append(wire);packet=Parser().feed(wire)[0];op=packet.payload[0]
                if op==1:
                    # INFO payload, exactly the same fields as firmware.
                    payload=struct.pack('<4B9HBBIB',6,2,0,2,3200,32000,100,8000,2,20,20,5110,0x4991,16,3,115200,4)
                    reply=encode(4,packet.sequence,payload)
                elif op==2:
                    payload=bytearray(77);struct.pack_into('<H',payload,48,4)
                    reply=encode(5,packet.sequence,payload)
                else:
                    if op==31:self.total=struct.unpack_from('<I',packet.payload,1)[0];detail=b'READY'
                    elif op==32:
                        off=struct.unpack_from('<I',packet.payload,1)[0]
                        if off==self.received:self.received+=len(packet.payload)-5
                        detail=str(self.received).encode()
                    elif op==30:detail=f'{self.received}/{self.total}/0'.encode()
                    elif op==33:detail=b'VERIFIED'
                    elif op==34:detail=b'REBOOTING'
                    else:detail=b'OFF'
                    reply=encode(2,packet.sequence,bytes([op])+detail)
                self.buffer.extend(reply)
        first=UpgradePort();session=SerialSession(first,True)
        def factory(**kwargs):return SerialSession(UpgradePort(),True)
        with patch('updater_protocol.time.sleep',lambda _:None):
            result=perform_upgrade('MOCK',image,factory,lambda *args:None,initial_port=session)
        self.assertEqual(result.new_version,'6.2.0');self.assertEqual(first.received,len(data))
        self.assertFalse(first.is_open);self.assertTrue(all(x.startswith(MAGIC) for x in first.writes))

