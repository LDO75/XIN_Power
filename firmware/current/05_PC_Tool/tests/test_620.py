    def test_same_sequence_retry_and_duplicate_reply(self):
        port=FakePort();s=SerialSession(port,True);s.send('CAL POINT STEP -1');wire=port.writes[-1]
        s.pending[3]=0;s.poll();self.assertEqual(port.writes[-1],wire)
        seq=s.pending[0];ack=encode(2,seq,b'\x10DAC_APPLIED');port.buffer.extend(ack+ack)
        self.assertEqual(len(s.poll()),1);self.assertIsNone(s.pending)
        # Multiple distinct diagnostic packets in one reply are retained.
        s.send('DIAG');seq=s.pending[0];port.buffer.extend(encode(11,seq,b'USB')+encode(11,seq,b'BT'))
        self.assertEqual(len(s.poll()),2)
